// Finds a place by its id. Returns undefined if there is no match.
function findPlace(placeId) {
  return places.find(function (place) {
    return place.id === placeId;
  });
}

// Returns { distance, time } between two towns, or undefined. Works in both directions.
function getTownTravel(townA, townB) {
  return townTravel[townA + "-" + townB] || townTravel[townB + "-" + townA];
}

// Returns the link for the map iframe.
function getMapUrl(place) {
  if (place.map !== "") {
    return place.map;
  }
  const search = place.name + ", " + place.town + ", Tarlac, Philippines";
  return "https://www.google.com/maps?q=" + encodeURIComponent(search) + "&output=embed";
}

// Returns a Google Maps ROUTE link from one town to another.
// Used for the route map on the Navigate page.
function getRouteMapUrl(start, destination) {
  const from = start + ", Tarlac, Philippines";
  const to = destination + ", Tarlac, Philippines";
  return "https://www.google.com/maps?saddr=" + encodeURIComponent(from) +
         "&daddr=" + encodeURIComponent(to) + "&output=embed";
}

// Looks for the photo of a place and calls callback(url) with the first one that exists.

function findPlaceImage(place, callback) {
  const sources = [];
  if (place.image !== "") {
    sources.push(place.image);
  } else {
    for (const ext of ["jpg", "png", "jpeg", "webp"]) {
      sources.push("images/" + place.id + "." + ext);
    }
  }

  let index = 0;
  function tryNext() {
    if (index >= sources.length) {
      return;
    }
    const url = sources[index];
    const test = new Image();
    test.onload = function () {
      callback(url);
    };
    test.onerror = function () {
      index = index + 1;
      tryNext();
    };
    test.src = url;
  }
  tryNext();
}

// Shows the place photo in an <img> element. The image stays hidden if there is no photo.
function loadPlaceImage(img, place) {
  img.hidden = true;
  findPlaceImage(place, function (url) {
    img.src = url;
    img.alt = place.name;
    img.hidden = false;
  });
}
